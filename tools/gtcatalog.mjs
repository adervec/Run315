// Regenerates js/gtcatalog.js -- the slice of GymTracker's exercise catalogue Run315 needs to
// read a GymTracker session: a session stores only variation uuids, and the names, the
// muscle-group split and the tracking mode live in gym-tracker.html, not in the synced file.
//
//   node tools/gtcatalog.mjs "<path to>/GymTracker/gym-tracker.html"
//
// It evaluates GymTracker's own tables (FAMILIES, BP_MAP, MUSCLE_GROUPS_MODEL, MUSCLE_CONTRIB)
// and applies GymTracker's own rules (getBP, muscleContribForVar's even-split fallback, exMode's
// title regexes), so the result says what GymTracker would say. Re-run when GymTracker adds
// exercises; unknown uuids degrade to "Unknown exercise, no muscle groups" in Run315.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(process.argv[2], 'utf8');
// `const NAME = <literal>;` -> the literal, cut at the first line that closes it at column 0.
function literal(name) {
  const i = src.indexOf(`\nconst ${name} = `);
  if (i < 0) throw new Error('not found: ' + name);
  const start = src.indexOf('=', i) + 1;
  const first = src.slice(start, src.indexOf('\n', start));
  // FAMILIES is one (huge) line; the others span lines and close with `};` / `];` at column 0.
  const body = /;\s*$/.test(first) ? first.replace(/;\s*$/, '')
    : src.slice(start, start + src.slice(start).search(/\n[\]}];/) + 2);
  return new Function('return (' + body + ')')();
}
const FAMILIES = literal('FAMILIES'), BP_MAP = literal('BP_MAP');
const MODEL = literal('MUSCLE_GROUPS_MODEL'), CONTRIB = literal('MUSCLE_CONTRIB');
const FOREARM = new Set(['grip-training', 'wrist-curl']);

const groupOf = {};
for (const g of MODEL) for (const mu of g.muscles) {
  groupOf[mu.id] = g.group;
  for (const h of mu.heads || []) groupOf[h.id] = g.group;
}
const bpOf = f => (FOREARM.has(f.id) ? 'forearms' : BP_MAP[`${f.mega}::${f.sub}`] || 'other');
// Fractional sets per body-part group for one set of this family (GymTracker's muscleContribForVar,
// rolled up to groups the way bpSessionLoad does).
function groups(f) {
  const out = {};
  if (CONTRIB[f.id]) {
    for (const [m, v] of Object.entries(CONTRIB[f.id])) if (groupOf[m]) out[groupOf[m]] = +((out[groupOf[m]] || 0) + v).toFixed(3);
  } else if (MODEL.some(g => g.group === bpOf(f))) out[bpOf(f)] = 1;
  return out;
}
// GymTracker's exMode(): t = time (reps hold seconds), d = distance, b = bodyweight (w = added load).
function mode(title, fid) {
  const t = (title || '').toLowerCase();
  if (/\b(dead ?hang|hang|hold|plank|l-?sit|wall sit|isometric|iso hold)\b/.test(t)) return 't';
  if (fid === 'carries' || /\b(carry|carries|farmer|yoke|suitcase carry|waiter|sled (push|drag|pull))\b/.test(t)) return 'd';
  if (/\b(pull-?up|chin-?up|dip|muscle-?up|push-?up|inverted row|pistol|nordic)\b/.test(t) && !/machine|assisted|lat ?pulldown|banded/.test(t)) return 'b';
  return '';
}

const fam = FAMILIES.map(f => [f.id, f.title, bpOf(f), groups(f), f.mega === 'cardio' ? 1 : 0]);
const famIx = new Map(FAMILIES.map((f, i) => [f.id, i]));
const vars = {};
for (const f of FAMILIES) for (const v of f.variations) {
  const k = v.uuid.slice(0, 8);
  if (vars[k]) throw new Error('uuid prefix collision: ' + k);
  vars[k] = [famIx.get(f.id), v.title, mode(v.title, f.id)];
}
const out = `// GENERATED by tools/gtcatalog.mjs from GymTracker's gym-tracker.html -- do not edit by hand.
// FAMILIES: [id, title, body part, {group: fractional sets per set}, isCardio]
// VARS: first 8 hex of the variation uuid -> [family index, title, mode ('' | t time | d distance | b bodyweight)]
export const FAMILIES = ${JSON.stringify(fam)};
export const VARS = ${JSON.stringify(vars)};
`;
writeFileSync(new URL('../js/gtcatalog.js', import.meta.url), out);
console.log(`${fam.length} families, ${Object.keys(vars).length} variations, ${out.length} bytes`);
